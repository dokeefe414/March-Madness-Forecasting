"""Pin and verify the public community mirror of Kaggle historical men's CSVs.

No Kaggle credentials required. RAW CSVs remain gitignored; public derived JSON
is generated by research/forecast/history.py. The source repository is not
affiliated with the NCAA or Kaggle.
"""
from __future__ import annotations

import argparse
import hashlib
import urllib.request
from pathlib import Path

COMMIT = "f8c521735ec41580711ce2d3e27dfd40f24e9e29"
RAW_BASE = (
    "https://raw.githubusercontent.com/Andreachurchwell/"
    f"march-madness-bracket-simulator/{COMMIT}/data/raw/"
)
# Git object IDs are content hashes, not optional advisory checks.
FILES = {
    "MTeams.csv": "2cac68eed13ce52cb5c1812611b6602be3201dd3",
    "MRegularSeasonCompactResults.csv": "8cb968344260ded5ec9624afd2aea3d404313820",
    "MNCAATourneyCompactResults.csv": "b0ccf8a1739ff71cfa90bd02082a4c435ba8a9d5",
    "MNCAATourneySeeds.csv": "9dc0e89369a7e1d6805d361bb04d35e88ab803f9",
    "2026_bracket_results.csv": "3fa6c9d4a7c34045a02215b1d9a0dae4e969c223",
    "bracket_2026.csv": "782d8d51e839defbeca4a238476fd12db8870037",
}


def git_blob_sha(content: bytes) -> str:
    prefix = f"blob {len(content)}\0".encode()
    return hashlib.sha1(prefix + content).hexdigest()


def download_all(destination: Path) -> None:
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    for file_name, expected_sha in FILES.items():
        target = destination / file_name
        if target.exists() and git_blob_sha(target.read_bytes()) == expected_sha:
            print(f"Verified cached {file_name}")
            continue
        with urllib.request.urlopen(RAW_BASE + file_name, timeout=90) as response:
            content = response.read()
        actual_sha = git_blob_sha(content)
        if actual_sha != expected_sha:
            raise ValueError(f"{file_name} Git blob mismatch: {actual_sha} != {expected_sha}")
        target.write_bytes(content)
        print(f"Fetched {file_name}: {len(content):,} bytes, verified {actual_sha}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Download and verify pinned Kaggle mirror files")
    parser.add_argument("--out-dir", type=Path, default=Path("research/data/raw"))
    args = parser.parse_args()
    download_all(args.out_dir)


if __name__ == "__main__":
    main()
